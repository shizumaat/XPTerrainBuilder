"""Read the text files exchanged with Triangle4XP (``.node``, ``.poly``, ``.ele``).

Vertex numbers inside segments and triangles are kept as Triangle numbers
them (1-based in Ortho4XP); the callers convert.  Every reader checks the
parsed count against the file's own header.
"""

from dataclasses import dataclass
import numpy as np

from O4_Num_Text import parse_numbers, write_rows

__all__ = [
    "ATTRIBUTE_INTEGRAL_TOL",
    "Elements",
    "NodeTable",
    "TriangleFormatError",
    "read_ele_text",
    "read_node_count",
    "read_node_text",
    "read_poly_segments",
    "triangle_attributes",
    "write_node_text",
]

#: A REAL attribute within this of an integer IS that integer (16.0000001
#: is RUNWAY); anything else is a measured degeneracy (see
#: ``O4_Mesh_Utils.read_triangle_attribute``, which keeps the per-text law).
ATTRIBUTE_INTEGRAL_TOL = 1e-6


class TriangleFormatError(ValueError):
    """A Triangle text file is malformed."""


@dataclass(frozen=True)
class NodeTable:
    """A ``.node`` file: ``ids`` as written, ``values`` the remaining
    columns (x, y, attributes, markers) as float64, and the header and
    trailer lines verbatim (``\\n`` line ends; the trailer is the line after
    the last vertex, Triangle's ``# Generated by`` comment, or ``""``)."""

    ids: np.ndarray
    values: np.ndarray
    header_line: str
    trailer_line: str

    @property
    def n_vertices(self) -> int:
        return int(self.ids.shape[0])

    @property
    def xy(self) -> np.ndarray:
        return self.values[:, :2]


@dataclass(frozen=True)
class Elements:
    """An ``.ele`` file: ``triangles`` (T, corners) int64 vertex numbers as
    written, ``attributes`` (T, n_attrs) float64."""

    triangles: np.ndarray
    attributes: np.ndarray

    @property
    def n_triangles(self) -> int:
        return int(self.triangles.shape[0])


def _read_text(path) -> bytes:
    with open(path, "rb") as handle:
        data = handle.read()
    if b"\r" in data[:256]:
        # Triangle4XP writes in text mode: CRLF on Windows.
        data = data.replace(b"\r\n", b"\n")
    return data


def _header(data: bytes, what) -> tuple:
    """``(ints of the first line, offset after it, the line as text)``."""
    end = data.find(b"\n")
    end = len(data) if end < 0 else end + 1
    line = data[:end]
    try:
        values = tuple(int(token) for token in line.split())
    except ValueError:
        raise TriangleFormatError(f"{what}: bad header {line!r}") from None
    if not values:
        raise TriangleFormatError(f"{what}: empty file")
    return values, end, line.decode("ascii")


def _body(data: bytes, start: int) -> tuple:
    """The numeric rows after ``start`` up to Triangle's trailing ``#``
    comment, and that comment's first line (``""`` when there is none)."""
    stop = data.find(b"#", start)
    if stop < 0:
        return data[start:], ""
    eol = data.find(b"\n", stop)
    eol = len(data) if eol < 0 else eol + 1
    return data[start:stop], data[stop:eol].decode("ascii", "replace")


def _rows(block: bytes, count: int, width: int, dtype, what) -> np.ndarray:
    values = parse_numbers(block, dtype) if block.strip() else np.zeros(0, dtype)
    if values.size != count * width:
        raise TriangleFormatError(
            f"{what}: expected {count} rows of {width} values, parsed {values.size}")
    return values.reshape(count, width)


def read_node_count(path) -> int:
    """The vertex count a ``.node`` file announces (its first field)."""
    with open(path, "rb") as handle:
        return int(handle.readline().split()[0])


def read_node_text(path) -> NodeTable:
    """Read a Triangle text ``.node`` file (input or Triangle4XP output)."""
    data = _read_text(path)
    (n, *rest), start, header_line = _header(data, path)
    dim, n_attrs, n_markers = (list(rest) + [2, 0, 0])[:3]
    if dim != 2:
        raise TriangleFormatError(f"{path}: only 2-D node files are supported")
    block, trailer = _body(data, start)
    table = _rows(block, n, 1 + 2 + n_attrs + n_markers, np.float64, path)
    return NodeTable(ids=table[:, 0].astype(np.int64),
                     values=np.ascontiguousarray(table[:, 1:]),
                     header_line=header_line, trailer_line=trailer)


def _strict_ints(table: np.ndarray, what) -> np.ndarray:
    as_int = table.astype(np.int64)
    if not np.array_equal(as_int, table):
        raise ValueError(f"{what}: a vertex number is not an integer")
    return as_int


def read_ele_text(path) -> Elements:
    """Read a Triangle text ``.ele`` file.  Vertex numbers are strict
    integers (a fractional one is a corrupt file: ``ValueError``); the
    attribute columns are REAL, as Triangle declares them."""
    data = _read_text(path)
    (n, *rest), start, _ = _header(data, path)
    corners, n_attrs = (list(rest) + [3, 0])[:2]
    block, _ = _body(data, start)
    width = 1 + corners + n_attrs
    try:
        table = _rows(block, n, width, np.int64, path)
        attributes = table[:, 1 + corners:].astype(np.float64)
        triangles = table[:, 1:1 + corners]
    except ValueError:
        # A REAL attribute (a degenerate sliver's 1.4375) is in the file.
        table = _rows(block, n, width, np.float64, path)
        attributes = table[:, 1 + corners:]
        triangles = _strict_ints(table[:, 1:1 + corners], path)
    return Elements(triangles=np.ascontiguousarray(triangles),
                    attributes=np.ascontiguousarray(attributes))


def triangle_attributes(values: np.ndarray, dummy: int = 0) -> tuple:
    """``(attributes int64, is_integral bool)`` for a REAL attribute column:
    an integral value (within ``ATTRIBUTE_INTEGRAL_TOL``) is its int, any
    other (fractional, non-finite) is ``dummy`` and not integral — the law
    ``O4_Mesh_Utils.read_triangle_attribute`` applies to one text."""
    values = np.asarray(values, dtype=np.float64)
    finite = np.isfinite(values)
    rounded = np.where(finite, np.round(np.where(finite, values, 0.0)), 0.0)
    integral = finite & (np.abs(values - rounded) <= ATTRIBUTE_INTEGRAL_TOL)
    return np.where(integral, rounded, dummy).astype(np.int64), integral


def read_poly_segments(path) -> tuple:
    """``(segments (m, 2) int64 as written, markers (m,) int64 or None)`` of
    a ``.poly`` whose vertices live in the ``.node`` (Ortho4XP's layout:
    ``0 2 1 0``, a blank line, then the segment section)."""
    lines = _read_text(path).split(b"\n")
    index = 0
    while not lines[index].strip() or lines[index].startswith(b"0 2"):
        index += 1
    fields = lines[index].split()
    n_segments = int(fields[0])
    with_markers = len(fields) > 1 and int(fields[1]) > 0
    rows = lines[index + 1:index + 1 + n_segments]
    width = 4 if with_markers else 3
    table = _rows(b" ".join(rows), n_segments, width, np.int64, path)
    return (np.ascontiguousarray(table[:, 1:3]),
            table[:, 3].copy() if with_markers else None)



def write_node_text(path, header_line, values, trailer_line) -> None:
    """Write a ``.node`` back: ``header_line``, one row per vertex numbered
    from 1 with every column of ``values`` as ``%.15f``, ``trailer_line``
    (the post-processed ``.1.node``'s exact text)."""
    values = np.asarray(values, dtype=np.float64)
    table = np.empty((values.shape[0], values.shape[1] + 1))
    table[:, 0] = np.arange(1, values.shape[0] + 1)
    table[:, 1:] = values
    row_format = "%d" + " %.15f" * values.shape[1] + "\n"
    with open(path, "w", encoding="ascii", newline="\n") as handle:
        handle.write(header_line)
        write_rows(handle, row_format, table)
        handle.write(trailer_line)
