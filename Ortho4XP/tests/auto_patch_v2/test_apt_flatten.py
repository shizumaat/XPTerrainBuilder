"""THE FLATTEN FLAG (#1916, RULINGS 2026-10-20ac): removed from a pack's
apt.dat whenever the app modifies the pack, kept as the shipped backup,
read back as shipped by every block reader (the flat-design witness keeps
the author's flag), put back by Restore originals, and never written over
a pack the user updated.

Synthetic ``tmp_path`` packs only; no network, no corpus, no X-Plane.
"""
from __future__ import annotations

import os

import pytest
from auto_patch_v2.airport import apt_dat as AD
from auto_patch_v2.airport import apt_flatten as AF
from auto_patch_v2.airport import backup_state as B
from auto_patch_v2.airport.pack import flatten_declared
from auto_patch_v2.model.placement import BACKUP_SUFFIX

APT = ("I\n1100 Generated by WorldEditor\n\n"
       "1      12 0 0 OTST Test Field\n"
       "1302 city Nowhere\n"
       "1302 flatten 1\r\n"
       "100 30.00 1 0 0.25 0 2 0 09 25.00000 51.00000 0 0 1 0 0 0 "
       "27 25.00000 51.01000 0 0 1 0 0 0\n"
       "99\n")


@pytest.fixture
def apt(tmp_path):
    pack = tmp_path / "Custom Scenery" / "Test Pack"
    path = pack / "Earth nav data" / "apt.dat"
    path.parent.mkdir(parents=True)
    path.write_bytes(APT.encode("utf-8"))
    B.invalidate_memo()
    yield path
    B.invalidate_memo()


def test_the_strip_removes_only_the_flatten_row(apt):
    shipped = apt.read_bytes()
    assert AF.strip_flatten(str(apt)) == "removed"
    live = apt.read_bytes()
    assert b"1302 flatten" not in live
    assert live == shipped.replace(b"1302 flatten 1\r\n", b"")
    assert (apt.parent / ("apt.dat" + BACKUP_SUFFIX)).read_bytes() == shipped
    assert AF.classify(str(apt)).state is B.State.OURS


def test_a_second_strip_writes_nothing(apt):
    AF.strip_flatten(str(apt))
    stat = os.stat(apt)
    assert AF.strip_flatten(str(apt)) == "removed_before"
    assert os.stat(apt).st_mtime_ns == stat.st_mtime_ns


def test_an_apt_dat_without_the_flag_is_never_touched(apt):
    apt.write_bytes(APT.replace("1302 flatten 1\r\n", "1302 flatten 0\n")
                    .encode("utf-8"))
    assert AF.strip_flatten(str(apt)) == ""
    assert not (apt.parent / ("apt.dat" + BACKUP_SUFFIX)).exists()


def test_readers_read_the_shipped_file(apt):
    before = AD.read_airport_block(str(apt), "OTST")
    mtime = AF.read_mtime(str(apt))
    AF.strip_flatten(str(apt))
    after = AD.read_airport_block(str(apt), "OTST")
    assert after == before, "the airport's signature does not move"
    assert flatten_declared(after), "the flat-design witness keeps the flag"
    assert AF.read_mtime(str(apt)) == mtime, "the strip is no pack update"


def test_restore_originals_puts_the_flag_back(apt):
    from auto_patch import object_rebake as OR
    shipped = apt.read_bytes()
    AF.strip_flatten(str(apt))
    out = OR.restore_detail(str(apt.parent.parent))
    assert out["restored"] == 1
    assert apt.read_bytes() == shipped
    assert AF.classify(str(apt)).state is B.State.PRISTINE


def test_a_pack_the_user_updated_is_never_reverted(apt):
    from auto_patch import object_rebake as OR
    AF.strip_flatten(str(apt))
    newer = APT.replace("Test Field", "Test Field v2").encode("utf-8")
    apt.write_bytes(newer)
    assert AF.classify(str(apt)).state is B.State.REPLACED
    assert AF.read_path(str(apt)) == str(apt), "the user's file is read"
    assert OR.restore_detail(str(apt.parent.parent))["kept_changed"] == 1
    assert apt.read_bytes() == newer
    # the next modification retires the stale backup and keeps the new one
    assert AF.strip_flatten(str(apt)) == "removed"
    assert (apt.parent / ("apt.dat" + BACKUP_SUFFIX)).read_bytes() == newer
    assert [n for n in os.listdir(apt.parent) if ".superseded-" in n]


def test_the_pack_state_without_a_write(apt):
    pack = str(apt.parent.parent)
    assert AF.pack_flatten(pack, write=False) == "found"
    assert b"1302 flatten 1" in apt.read_bytes()
    assert AF.pack_flatten(pack, write=True) == "removed"
    assert AF.pack_flatten(pack, write=False) == "removed_before"
