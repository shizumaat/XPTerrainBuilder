def _cell():
    return shapely.set_precision(shapely.from_wkb(bytes.fromhex(_CELL_WKB)), 0.01)


def test_grid_band_is_the_failing_operand():
    assert not _cell().boundary.buffer(1.0).is_valid


def test_weld_band_is_valid_and_exact():
    cell = _cell()
    band = _weld_band(cell, 1.0)
    assert band.is_valid
    exact = shapely.set_precision(cell, 0.0).boundary.buffer(1.0)
    assert shapely.symmetric_difference(band, exact).area < 1e-6


def test_contact_reads_without_raising():
    cell = _cell()
    face = Polygon(cell.exterior.coords).buffer(0.5)
    contact = face.boundary.intersection(_weld_band(cell, 1.0))
    assert contact.length > 0.0
