def _weld(**kw):
    cell = shapely.from_wkb(bytes.fromhex(_CELL_WKB))
    senior = shapely.from_wkb(bytes.fromhex(_SENIOR_WKB))
    return weld._weld_one(cell, senior, 1.0, None, (), 0.001)[0], cell


def test_buffer_zero_repair_is_the_failing_producer(monkeypatch):
    monkeypatch.setattr(weld, "valid_area", lambda g: g.buffer(0))
    q, _cell = _weld()
    assert q is not None and not q.is_valid


def test_welded_cell_is_valid_and_keeps_its_area():
    q, cell = _weld()
    assert q is not None and q.is_valid and q.geom_type == "Polygon"
    assert q.area >= 0.5 * cell.area
