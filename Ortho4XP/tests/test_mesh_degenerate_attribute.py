# write_mesh_file — the .mesh attribute column stays integral


def test_mesh_file_attribute_column_is_normalised(tmp_path, monkeypatch):
    """Every reader of the written mesh (``read_mesh_file``, the mask
    builders, auto_patch's mesh sampler) parses the attribute as an int,
    so the float never reaches them."""
    tile = _make_tile(tmp_path)
    _seed_node_file(tile)
    _seed_ele_file(tile, ["1.4375", "16.0", "8"])
    monkeypatch.setattr(UI, "lvprint", lambda *args: None)
    vertices = O4_Mesh_Utils.post_process_nodes_altitudes(tile)

    O4_Mesh_Utils.write_mesh_file(tile, vertices)

    mesh_path = FNAMES.mesh_file(tile.build_dir, tile.lat, tile.lon)
    with open(mesh_path, "r") as handle:
        lines = handle.read().splitlines()
    triangle_header_index = lines.index("Triangles")
    triangle_rows = lines[
        triangle_header_index + 2 : triangle_header_index + 5
    ]
    assert triangle_rows == ["1 2 3 0", "1 2 3 16", "1 2 3 8"]

    (_, _, _, nbr_tris, _, tri_types) = O4_Mesh_Utils.read_mesh_file(
        mesh_path
    )
    assert nbr_tris == 3
    assert list(tri_types) == [ATTR["DUMMY"], 16, ATTR["INTERP_ALT"]]
