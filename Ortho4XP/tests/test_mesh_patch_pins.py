"""A PATCH-PINNED VERTEX KEEPS ITS PATCH VALUE IN THE MESH (#2034).

LGAV +37+023: node -6749, an open ``structure_rim`` foot outside every
patch ring, carried 66.82 m into the ``.node`` and came out of the mesh
step at the DEM's 77.21 m: its six triangles were all attribute 0, and
``post_process_nodes_altitudes`` copied column 5 only through INTERP_ALT
triangles.  KIAH +29-096 had three more (``tunnel_wall`` feet).  See
``src/O4_Mesh_Pins.py``.

Hermetic: the ``.node`` / ``.ele`` harness of
``tests/test_mesh_water_precedence.py`` plus the input ``.node`` /
``.poly`` the pinned set is read from.
"""
from __future__ import annotations

import types

import O4_File_Names as FNAMES
import O4_Mesh_Pins as PINS
import O4_Mesh_Utils as MESH
import O4_Triangle_Binary as TRI_BIN
import O4_UI_Utils as UI
import O4_Vector_Utils as VECT
import pytest

ATTR = VECT.Vector_Map.dico_attributes
RING = MESH.PATCH_RING_MARKER

DEM = 77.21
CARRIED = 66.82

#: 0-2 carry the INTERP_ALT-region triangle (an apt.dat RUNWAY region, so
#: the R18-1b patch-interior block stays out of the way); 3 and 4 are
#: corners of attribute-0 triangles only.
CORNERS = [(0.0, 0.0), (0.001, 0.0), (0.0, 0.001), (0.001, 0.001),
           (0.002, 0.001)]


def _tile(build_directory) -> types.SimpleNamespace:
    return types.SimpleNamespace(build_dir=str(build_directory), lat=37,
                                 lon=23, iterate=0, water_smoothing=0,
                                 sea_smoothing_mode="zero")


def _seed(tile, ring_edges, outside_attr=0) -> None:
    n = len(CORNERS)
    with open(FNAMES.input_node_file(tile), "w", encoding="utf-8",
              newline="") as handle:
        handle.write(f"{n} 2 1 0\n")
        for index, (x, y) in enumerate(CORNERS):
            handle.write("%d %.9f %.9f %.9f\n" % (index + 1, x, y, CARRIED))
    with open(FNAMES.input_poly_file(tile), "w", encoding="utf-8",
              newline="") as handle:
        handle.write("0 2 1 0\n\n%d 1\n" % len(ring_edges))
        for k, (a, b) in enumerate(ring_edges):
            handle.write("%d %d %d %d\n" % (k + 1, a, b, RING))
        handle.write("\n0\n\n0\n")
    with open(FNAMES.output_node_file(tile), "w", encoding="utf-8",
              newline="") as handle:
        handle.write(f"{n} 2 4 0\n")
        for index, (x, y) in enumerate(CORNERS):
            handle.write("%d %.9f %.9f %.15f 0.25 0.25 %.15f\n"
                         % (index + 1, x, y, DEM, CARRIED))
        handle.write("# Generated by a test\n")
    with open(FNAMES.output_ele_file(tile), "w", encoding="utf-8",
              newline="") as handle:
        handle.write("3 3 1\n")
        handle.write("1 1 2 3 %d\n" % ATTR["RUNWAY"])
        handle.write("2 2 4 3 %d\n" % outside_attr)
        handle.write("3 2 5 4 %d\n" % outside_attr)
        handle.write("# Generated by a test\n")


def _run(tile, monkeypatch):
    monkeypatch.setattr(UI, "lvprint", lambda *a, **k: None)
    monkeypatch.setattr(UI, "vprint", lambda *a, **k: None)
    return MESH.post_process_nodes_altitudes(tile)


def test_a_pinned_vertex_on_attribute_0_triangles_only_takes_its_value(
        tmp_path, monkeypatch):
    """The LGAV -6749 shape: an open rim 4-5 outside every ring."""
    tile = _tile(tmp_path)
    _seed(tile, [(4, 5)])
    v = _run(tile, monkeypatch)
    assert v[6 * 3 + 2] == pytest.approx(CARRIED)
    assert v[6 * 4 + 2] == pytest.approx(CARRIED)
    assert (v[6 * 3 + 3], v[6 * 3 + 4]) == (0, 0)


def test_an_unpinned_vertex_on_attribute_0_keeps_the_dem(tmp_path,
                                                          monkeypatch):
    tile = _tile(tmp_path)
    _seed(tile, [])
    v = _run(tile, monkeypatch)
    assert v[6 * 1 + 2] == pytest.approx(CARRIED)  # a RUNWAY corner
    assert v[6 * 3 + 2] == pytest.approx(DEM)
    assert v[6 * 4 + 2] == pytest.approx(DEM)


def test_a_pinned_vertex_on_water_keeps_the_water_datum(tmp_path,
                                                        monkeypatch):
    """RULINGS 2026-09-09z (3): the water bit outranks the patch."""
    tile = _tile(tmp_path)
    _seed(tile, [(4, 5)], outside_attr=ATTR["SEA"])
    v = _run(tile, monkeypatch)
    assert v[6 * 3 + 2] == 0.0
    assert v[6 * 4 + 2] == 0.0


def test_unreadable_inputs_are_a_no_op(tmp_path, monkeypatch):
    tile = _tile(tmp_path)
    _seed(tile, [(4, 5)])
    monkeypatch.setattr(MESH.FNAMES, "input_poly_file",
                        lambda t: "/nonexistent/x.poly")
    v = _run(tile, monkeypatch)
    assert v[6 * 4 + 2] == pytest.approx(DEM)


def test_the_union_is_unchanged(tmp_path):
    """``patch_valued_vertex_indices`` is still ring endpoints + clamped."""
    tile = _tile(tmp_path)
    _seed(tile, [(4, 5)])
    nodes = TRI_BIN.read_node(FNAMES.output_node_file(tile))
    vertices = nodes.values[:, :6].ravel()
    assert MESH.patch_valued_vertex_indices(tile, vertices) == {3, 4}
    assert MESH._patch_ring_vertex_indices(tile, vertices) == ({3, 4}, set())


def test_the_pavement_shore_vertex_is_pinned_on_water():
    vertices = [0.0, 0.0, 1.0, 0.5, 0.5, 6.0] * 2
    got = PINS.pin_stranded_patch_vertices(
        vertices, {0, 1}, set(), water_valued={0, 1}, pavement_shore={1})
    assert got == [1]
    assert vertices[2] == 1.0 and vertices[8] == 6.0


def test_a_vertex_an_interp_alt_triangle_reached_is_left_alone():
    vertices = [0.0, 0.0, 1.0, 0.5, 0.5, 6.0] * 3
    got = PINS.pin_stranded_patch_vertices(
        vertices, {0, 1, 2}, {(0, 1, 2)}, set(), set())
    assert got == []
    assert vertices[2] == 1.0
