"""A PAVEMENT RING vertex on the shore keeps the PAVEMENT value (#945).

Owner sim read, VMMC 2026-10-19: the taxiways that cross from the apron to
the runway — viaducts over open water — "have a centerline ridge at the
right height and then angle steeply down to the water instead of staying
flat across the paved width".  Measured on the owner's built
``Data+22+113.mesh``: the north connector's centreline at 5.45 m, both
paved edges at 0.00 m, the patch ring there carrying 4.96..5.88 m.

The ring vertex is a corner of the INTERP_ALT pavement triangles inside
and of the sea-owned seawall band outside, so RULINGS 2026-09-09z (3)'s
per-vertex water datum levelled it to the sea.  The same ruling's words —
"only set pavement node elevations, then the DEM should grade into the
water" — keep a pavement node at its own value; the seawall band
(``O4_Vector_Map.SEAWALL_OFFSET_M`` out, at the water's level) carries the
drop.  A marked ring that is NOT pavement (a bank foot) keeps the water
datum, exactly as §18 S9 measured it.

Hermetic: the ``.node`` / ``.ele`` harness of
``tests/test_mesh_water_precedence.py``; the patch-ring readers are bound
to a two-triangle fixture.
"""
from __future__ import annotations

import types

import O4_File_Names as FNAMES
import O4_Mesh_Utils as MESH
import O4_UI_Utils as UI
import O4_Vector_Utils as VECT
from shapely.geometry import LineString

ATTR = VECT.Vector_Map.dico_attributes

#: The raw (DEM) column, the pavement's column-5 value, and the sea.
RAW_ELEVATION = 1.76
PAVEMENT_ELEVATION = 6.10

#: Vertices 0 and 1 are the pavement ring's shore edge; 2 is a ring
#: vertex on land; 3 is the seawall-band node at sea level.
CORNERS = [(0.0, 0.0), (0.001, 0.0), (0.0005, 0.001), (0.0005, -0.000005)]


def _tile(build_directory) -> types.SimpleNamespace:
    return types.SimpleNamespace(build_dir=str(build_directory), lat=22,
                                 lon=113, iterate=0, water_smoothing=0,
                                 sea_smoothing_mode="zero")


def _seed(tile) -> None:
    with open(FNAMES.output_node_file(tile), "w", encoding="utf-8",
              newline="") as handle:
        handle.write("4 2 4 0\n")
        for index, (dlon, dlat) in enumerate(CORNERS):
            carried = 0.0 if index == 3 else PAVEMENT_ELEVATION
            handle.write("%d %.15f %.15f %.15f 0 0 %.15f\n"
                         % (index + 1, dlon, dlat, RAW_ELEVATION, carried))
        handle.write("# Generated by a test\n")
    with open(FNAMES.output_ele_file(tile), "w", encoding="utf-8",
              newline="") as handle:
        handle.write("2 3 1\n")
        handle.write("1 1 2 3 %d\n" % ATTR["INTERP_ALT"])   # the pavement
        handle.write("2 1 2 4 %d\n" % ATTR["SEA"])          # the band
        handle.write("# Generated by a test\n")


def _bind(monkeypatch, pavement_lines) -> None:
    monkeypatch.setattr(UI, "lvprint", lambda *a, **k: None)
    monkeypatch.setattr(UI, "vprint", lambda *a, **k: None)
    monkeypatch.setattr(MESH, "patch_valued_vertex_indices",
                        lambda tile, vertices: {0, 1, 2})
    monkeypatch.setattr(MESH, "patch_coverage_polygon",
                        lambda tile: (object(), object()))
    monkeypatch.setattr(MESH, "triangles_inside_coverage",
                        lambda vertices, tris, covered: tris)
    monkeypatch.setattr(MESH, "patch_segment_split_values",
                        lambda *a, **k: {})
    monkeypatch.setattr(MESH, "interp_alt_ribbon_vertex_indices",
                        lambda tile: set())
    monkeypatch.setattr(MESH, "bank_annulus_blend_values", lambda *a, **k: {})
    monkeypatch.setattr(MESH, "audit_bank_annulus", lambda *a, **k: None)
    monkeypatch.setattr(MESH, "interpolate_free_interior_altitudes",
                        lambda *a, **k: 0)
    monkeypatch.setattr(MESH, "audit_interp_alt_extent", lambda *a, **k: None)
    monkeypatch.setattr(MESH, "bank_pavement_lines",
                        lambda tile: (pavement_lines, [], 0.0))


def _shore_line(tile) -> LineString:
    """The ring's shore edge in ``bank_pavement_lines``' isotropic frame."""
    scalx = MESH.cos((tile.lat + 0.5) * MESH.pi / 180)
    return LineString([(x * scalx, y) for x, y in CORNERS[:2]])


def test_the_pavement_edge_on_the_water_keeps_the_pavement_value(
        tmp_path, monkeypatch):
    tile = _tile(tmp_path)
    _seed(tile)
    _bind(monkeypatch, [_shore_line(tile)])
    z = MESH.post_process_nodes_altitudes(tile)[2::6]
    assert z[0] == PAVEMENT_ELEVATION and z[1] == PAVEMENT_ELEVATION, (
        "the paved edge must stay at the deck, not drop to the sea")
    assert z[2] == PAVEMENT_ELEVATION
    assert z[3] == 0.0, "the seawall node is water and stays at sea level"


def test_a_marked_ring_that_is_not_pavement_keeps_the_water_datum(
        tmp_path, monkeypatch):
    """No aeroway / highway way under the ring (a bank foot): §18 S9."""
    tile = _tile(tmp_path)
    _seed(tile)
    _bind(monkeypatch, [])
    z = MESH.post_process_nodes_altitudes(tile)[2::6]
    assert z[0] == 0.0 and z[1] == 0.0
    assert z[2] == PAVEMENT_ELEVATION
    assert z[3] == 0.0


def test_only_water_vertices_on_the_pavement_ring_are_returned(tmp_path,
                                                     monkeypatch):
    import numpy

    tile = _tile(tmp_path)
    vertices = numpy.zeros(6 * len(CORNERS))
    for index, (dlon, dlat) in enumerate(CORNERS):
        vertices[6 * index], vertices[6 * index + 1] = dlon, dlat
    monkeypatch.setattr(MESH, "bank_pavement_lines",
                        lambda t: ([_shore_line(tile)], [], 0.0))
    got = MESH.pavement_shore_vertices(tile, vertices, {0, 1, 3})
    assert got == {0, 1}
