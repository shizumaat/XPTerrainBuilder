"""The Viewfinder Panoramas coverage tables (issues #1974, #1933).

The 1 arc-second whitelist was a stale hand copy (35 zones; N29 Ireland,
N30 Isle of Man / N England, O30 Scotland missing), and the 3 arc-second
source had no table, so Iceland and Greenland tiles asked for
``dem3/P27.zip``, ``Q27.zip``, ``P22.zip`` -- which 404.  Both tables are
now generated by ``tools/refresh_viewfinder_coverage.py`` from the site's
coverage maps.  No network here: the shipped tables, the parser and the
refresh tool's page reader are pinned offline.
"""
from __future__ import annotations

import importlib.util
import os
import re
import sys

import O4_Airport_Elevation_Insets as INSETS
import pytest
from elevation_access import base_tiles as ea_base_tiles
from elevation_access.definitions import parse_archive_zones

_HERE = os.path.dirname(os.path.abspath(__file__))


PROVIDERS = os.path.normpath(os.path.join(_HERE, "..", "Providers", "Elevation"))
TOOL = os.path.normpath(
    os.path.join(_HERE, "..", "tools", "refresh_viewfinder_coverage.py"))
TABLES = {"dem1": "viewfinder_dem1_zones.txt",
          "dem3": "viewfinder_dem3_zones.txt"}
ZONE = re.compile(r"S?[A-Z]\d\d")
HISTORIC_DEM1 = (
    "L31,L32,L33,K32,O31,P31,N32,O32,P32,Q32,N33,O33,P33,Q33,R33,O34,P34,"
    "Q34,R34,O35,P35,Q35,R35,P36,Q36,R36,SL58,SI59,SJ59,SK59,SL59,SI60,"
    "SJ60,SK60,SL60").split(",")


def _tool():
    spec = importlib.util.spec_from_file_location("refresh_vfp", TOOL)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _table_text(name):
    with open(os.path.join(PROVIDERS, TABLES[name]), encoding="utf-8") as h:
        return h.read()


@pytest.fixture
def registry():
    return INSETS.initialize_elevation_providers_dict(PROVIDERS)


@pytest.mark.parametrize("name", sorted(TABLES))
def test_table_format_and_header(name):
    text = _table_text(name)
    header = [line for line in text.splitlines() if line.startswith("#")]
    assert any(line.startswith("# Source: https://viewfinderpanoramas.org/")
               for line in header)
    assert any(re.fullmatch(r"# Fetched: \d{4}-\d\d-\d\d", line)
               for line in header)
    tokens = [token for line in text.splitlines() if not line.startswith("#")
              for token in line.split(",")]
    assert tokens and all(ZONE.fullmatch(token) for token in tokens)
    assert len(tokens) == len(set(tokens))
    count = re.search(r"^# Zones: (\d+)$", text, re.MULTILINE)
    assert count and int(count.group(1)) == len(tokens)


def test_dem1_lists_the_zones_issue_1974_names_and_keeps_the_historic_ones():
    zones = parse_archive_zones(_table_text("dem1"))
    for code in ("N29", "N30", "O30", "P22", "P27", "Q27"):
        assert code in zones
    assert set(HISTORIC_DEM1) <= zones


def test_dem3_does_not_list_the_zones_that_404_issue_1933():
    zones = parse_archive_zones(_table_text("dem3"))
    for code in ("P22", "P27", "Q27"):
        assert code not in zones
    for code in ("N60", "J16", "L11", "C32"):
        assert code in zones


@pytest.mark.parametrize("tile, code", [
    ((54, -5), "N30"),     # Isle of Man (EGNS, #1973/#1974)
    ((53, -7), "N29"),     # Ireland
    ((57, -4), "O30"),     # Scotland
    ((63, -23), "P27"),    # BIKF, #1933
    ((64, -23), "Q27"),    # BIKA, #1933
    ((64, -52), "Q22"),    # BGGH, #1933
    ((61, -50), "P22"),    # South-west Greenland, #1933
])
def test_iceland_greenland_and_britain_resolve_to_dem1(registry, tile, code):
    lat, lon = tile
    assert ea_base_tiles.deferranti_archive_code(lat, lon) == code
    assert INSETS.resolve_base_definition(lat, lon, "View")["code"] == (
        "VIEWFINDER1")
    if code in ("P22", "P27", "Q27", "Q22"):
        assert not ea_base_tiles.base_definition_covers_tile(
            registry["VIEWFINDER3"], lat, lon)


def test_an_unreadable_zone_table_disables_the_source(tmp_path):
    (tmp_path / "VFPX.elv").write_text(
        "role=base\naccess_strategy=viewfinder_zip\n"
        "archive_zones_file=missing.txt\n", encoding="utf-8", newline="\n")
    parsed = INSETS.initialize_elevation_providers_dict(str(tmp_path))
    assert parsed["VFPX"]["enabled"] is False
    INSETS.initialize_elevation_providers_dict(PROVIDERS)


def test_legacy_inline_dem1_zones_still_parse(tmp_path):
    (tmp_path / "VFPX.elv").write_text(
        "role=base\naccess_strategy=viewfinder_zip\ndem1_zones=L31, L32\n",
        encoding="utf-8", newline="\n")
    parsed = INSETS.initialize_elevation_providers_dict(str(tmp_path))
    assert parsed["VFPX"]["archive_zones"] == frozenset({"L31", "L32"})
    INSETS.initialize_elevation_providers_dict(PROVIDERS)


def test_refresh_tool_reads_a_coverage_map_offline():
    tool = _tool()
    html = (
        '<area href="https://viewfinderpanoramas.org/dem3/N30.zip">'
        '<area href="https://viewfinderpanoramas.org/dem3/SK60.zip">'
        '<area href="https://viewfinderpanoramas.org/dem3/P32v2.zip">'
        '<area href="https://viewfinderpanoramas.org/dem3/ISL.zip">'
        '<area href="https://viewfinderpanoramas.org/A21.zip">'
        '<area href="https://viewfinderpanoramas.org/dem1/O30.zip">')
    zones, unprobed, others = tool.parse_coverage_map(html, "dem3")
    assert zones == {"N30", "SK60"}
    assert unprobed == {"P32", "A21", "O30"}
    assert others == {"dem3/P32v2.zip", "dem3/ISL.zip"}
    text = tool.format_table("dem3", "dem3", "https://example.invalid/map",
                             "2026-11-09", zones | {"P32"}, others, {"P32"})
    assert parse_archive_zones(text) == {"N30", "SK60", "P32"}
