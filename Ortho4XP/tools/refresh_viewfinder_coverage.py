"""Regenerate the Viewfinder Panoramas archive-coverage tables.

Issues #1974 and #1933: the 1 arc-second whitelist was a hand-kept copy
of the historic code (35 zones; the site now publishes 316) and the
3 arc-second source had no table at all, so it asked for archives that
do not exist (``dem3/P27.zip`` -> 404 for Iceland).  Both tables are now
generated from Viewfinder Panoramas' own linked coverage maps, one
archive code per letter+number zone, into

    Providers/Elevation/viewfinder_dem1_zones.txt   (VIEWFINDER1.elv)
    Providers/Elevation/viewfinder_dem3_zones.txt   (VIEWFINDER3.elv)

which the ``.elv`` files name through ``archive_zones_file=``.

The maps link a few archives this engine's tile -> archive mapping
(``deferranti_archive_code``) can never ask for -- regional ones such as
``ISL``, ``GL-East`` and revised editions such as ``P32v2``.  They are
recorded in the header, not listed.  Where the map links ONLY a revised
edition (``P32v2``) or links a zone archive outside its directory, the
plain ``<dir>/<code>.zip`` is probed with a one-byte ranged GET and
listed only when the server has it -- a few dozen requests, never a
download.

Network: this script is the ONE place the tables are fetched; the engine
never fetches them.  Run it by hand, review the diff, commit the tables.

    venv/bin/python tools/refresh_viewfinder_coverage.py [--no-probe] [--out-dir DIR]
"""

import argparse
import datetime
import os
import re
import sys
import urllib.error
import urllib.request

SITE = "https://viewfinderpanoramas.org/"

#: (table name, archive directory, coverage-map page)
TABLES = (
    ("dem1", "dem1", SITE + "Coverage%20map%20viewfinderpanoramas_org1.htm"),
    ("dem3", "dem3", SITE + "Coverage%20map%20viewfinderpanoramas_org3.htm"),
)

#: A zone code ``deferranti_archive_code`` can produce: an optional S,
#: a row letter, a two-digit column.
ZONE_CODE = re.compile(r"S?[A-Z]\d\d")

#: A revised edition of a zone archive (``P32v2``): its zone code.
REVISED_EDITION = re.compile(r"(S?[A-Z]\d\d)v\d+")

_HREF = re.compile(r'href="(?:https?://viewfinderpanoramas\.org/)?([^"]+\.zip)"',
                   re.IGNORECASE)

CODES_PER_LINE = 12


def parse_coverage_map(html, directory):
    """Read one coverage-map page.

    Returns ``(zones, unprobed, others)``: the zone codes linked inside
    ``directory``; zone codes the page implies but does not link there
    (a revised edition only, or a link outside the directory) and which
    a probe must confirm; and every other archive name, kept for the
    header.
    """
    zones, unprobed, others = set(), set(), set()
    for path in _HREF.findall(html):
        folder, _, file_name = path.rpartition("/")
        name = file_name[:-4]
        if ZONE_CODE.fullmatch(name):
            (zones if folder == directory else unprobed).add(name)
            continue
        others.add(path)
        revised = REVISED_EDITION.fullmatch(name)
        if revised and folder == directory:
            unprobed.add(revised.group(1))
    return zones, unprobed - zones, others


def archive_exists(url, timeout=30):
    """Does the server hold this archive?  One byte, never the body."""
    request = urllib.request.Request(url, headers={"Range": "bytes=0-0"})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return response.status in (200, 206)
    except urllib.error.HTTPError as error:
        if error.code in (404, 410):
            return False
        raise


def _zone_sort_key(code):
    southern = code.startswith("S")
    return (southern, code.lstrip("S")[0], int(code[-2:]))


def format_table(name, directory, page_url, date, zones, others, probed):
    """The table file text: a header, then the codes by row letter."""
    lines = [
        "# Viewfinder Panoramas %s archive codes (%s/<code>.zip)."
        % (name, directory),
        "# GENERATED by Ortho4XP/tools/refresh_viewfinder_coverage.py --"
        " do not hand-edit; re-run it.",
        "# Source: %s" % page_url,
        "# Fetched: %s" % date,
        "# Zones: %d" % len(zones),
    ]
    if probed:
        lines.append("# Confirmed by probe (not linked in %s/ on the map): %s"
                     % (directory, ", ".join(sorted(probed, key=_zone_sort_key))))
    if others:
        lines.append("# Linked but outside the zone grid (not used): %s"
                     % ", ".join(sorted(others)))
    rows = {}
    for code in sorted(zones, key=_zone_sort_key):
        rows.setdefault(code[:-2], []).append(code)
    for row in sorted(rows, key=lambda r: (r.startswith("S"), r.lstrip("S"))):
        codes = rows[row]
        for start in range(0, len(codes), CODES_PER_LINE):
            lines.append(",".join(codes[start:start + CODES_PER_LINE]))
    return "\n".join(lines) + "\n"


def _fetch(url, timeout=60):
    with urllib.request.urlopen(url, timeout=timeout) as response:
        return response.read().decode("utf-8", errors="replace")


def main(argv=None):
    here = os.path.dirname(os.path.abspath(__file__))
    sys.path.insert(0, os.path.join(here, os.pardir, "src"))
    import O4_Console_Encoding
    O4_Console_Encoding.configure_console_streams()
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--out-dir",
        default=os.path.join(here, os.pardir, "Providers", "Elevation"))
    parser.add_argument("--no-probe", action="store_true",
                        help="skip the one-byte probes of implied archives")
    args = parser.parse_args(argv)
    date = datetime.date.today().isoformat()
    for name, directory, page_url in TABLES:
        zones, unprobed, others = parse_coverage_map(_fetch(page_url),
                                                     directory)
        probed = set()
        if not args.no_probe:
            for code in sorted(unprobed, key=_zone_sort_key):
                url = "%s%s/%s.zip" % (SITE, directory, code)
                if archive_exists(url):
                    probed.add(code)
                print("  probe %s -> %s" % (url, code in probed))
        zones |= probed
        path = os.path.join(args.out_dir, "viewfinder_%s_zones.txt" % name)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(format_table(name, directory, page_url, date,
                                      zones, others, probed))
        print("%s: %d zones (%d by probe) -> %s"
              % (name, len(zones), len(probed), os.path.normpath(path)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
